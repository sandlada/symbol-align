/**
 * Generates the Rust and TypeScript language tables from `languages.json`.
 *
 * The JSON file is the single source of truth. Both generated modules contain
 * the exact same data, so the wrapper can answer profile lookups without a
 * round trip and the Rust core can align without a profile payload.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const packageRoot = new URL('..', import.meta.url);
const source = fileURLToPath(new URL('languages.json', packageRoot));
const rustTarget = fileURLToPath(new URL('rust/src/language_data.rs', packageRoot));
const typescriptTarget = fileURLToPath(new URL('src/generated/languages.ts', packageRoot));

/** Escapes a value so that it can be embedded in a Rust string literal. */
const rustString = (value) => JSON.stringify(value).replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) => `\\u{${hex}}`);

/** Emits one Rust string slice. */
const rustStrings = (values) => `&[${values.map((value) => rustString(value)).join(', ')}]`;

/** Emits one Rust block comment pair. */
const rustBlock = (block) => `BlockCommentData { open: ${rustString(block[0])}, close: ${rustString(block[1])} }`;

/** Emits one Rust string delimiter. */
const rustDelimiter = (delimiter) => `StringDelimiterData { open: ${rustString(delimiter.open)}, close: ${rustString(delimiter.close)}, escape: ${rustString(delimiter.escape)}, multiline: ${delimiter.multiline} }`;

/** Renders the Rust data module. */
const renderRust = (profiles) => `// Generated by scripts/generate-languages.mjs from languages.json - do not edit.
#![allow(clippy::unreadable_literal)]

/// A block comment delimiter pair.
pub struct BlockCommentData {
    pub open: &'static str,
    pub close: &'static str,
}

/// A string literal delimiter.
pub struct StringDelimiterData {
    pub open: &'static str,
    pub close: &'static str,
    pub escape: &'static str,
    pub multiline: bool,
}

/// One language profile exactly as it is published by the API.
pub struct LanguageProfileData {
    pub id: &'static str,
    pub name: &'static str,
    pub extensions: &'static [&'static str],
    pub line_comments: &'static [&'static str],
    pub block_comments: &'static [BlockCommentData],
    pub strings: &'static [StringDelimiterData],
    pub operators: &'static [&'static str],
    pub default_symbols: &'static [&'static str],
    pub declarations: &'static str,
}

/// Every supported language profile, in the order of the public LanguageId union.
pub static PROFILES: &[LanguageProfileData] = &[
${profiles
    .map(
        (profile) => `    LanguageProfileData {
        id: ${rustString(profile.id)},
        name: ${rustString(profile.name)},
        extensions: ${rustStrings(profile.extensions)},
        line_comments: ${rustStrings(profile.lineComments)},
        block_comments: &[${profile.blockComments.map(rustBlock).join(', ')}],
        strings: &[${profile.strings.map(rustDelimiter).join(', ')}],
        operators: ${rustStrings(profile.operators)},
        default_symbols: ${rustStrings(profile.defaultSymbols)},
        declarations: ${rustString(profile.declarations)},
    },`,
    )
    .join('\n')}
];
`;

/** Renders the TypeScript data module. */
const renderTypeScript = (profiles) => `// Generated by scripts/generate-languages.mjs from languages.json - do not edit.
import type { LanguageProfile } from '../types.js';

/** Every supported language profile, in the order of the public LanguageId union. */
export const languages = ${JSON.stringify(profiles, null, 4)} as const satisfies readonly LanguageProfile[];
`;

const profiles = JSON.parse(readFileSync(source, 'utf-8'));

writeFileSync(rustTarget, renderRust(profiles), 'utf-8');
writeFileSync(typescriptTarget, renderTypeScript(profiles), 'utf-8');
process.stdout.write(`Generated ${profiles.length} profiles for Rust and TypeScript\n`);
