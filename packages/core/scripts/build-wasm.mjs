/**
 * Builds the Rust core for wasm and inlines the module as base64.
 *
 * The generated TypeScript module is the only build artifact: the rest of the
 * package is plain TypeScript. Keeping the wasm payload inline means the
 * package works in Node.js, the browser, a worker and the VS Code extension
 * host without an asset loader or a platform-specific glue file.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const packageRoot = new URL('..', import.meta.url);
const rustRoot = fileURLToPath(new URL('rust', packageRoot));
const wasmPath = fileURLToPath(new URL('rust/target/wasm32-unknown-unknown/release/symbol_align_core.wasm', packageRoot));
const generatedDirectory = fileURLToPath(new URL('src/generated', packageRoot));
const generatedPath = fileURLToPath(new URL('src/generated/wasm-binary.ts', packageRoot));

const build = spawnSync('cargo', ['build', '--manifest-path', 'Cargo.toml', '--target', 'wasm32-unknown-unknown', '--release'], {
    cwd: rustRoot,
    stdio: 'inherit',
    env: process.env,
});

if (build.error !== undefined) {
    process.stderr.write(`Could not run cargo: ${build.error.message}\n`);
    process.exit(1);
}

if (build.status !== 0) {
    process.exit(build.status ?? 1);
}

const bytes = readFileSync(wasmPath);
const base64 = bytes.toString('base64');

mkdirSync(generatedDirectory, { recursive: true });
writeFileSync(generatedPath, `// Generated by scripts/build-wasm.mjs - do not edit.\nexport const WASM_BASE64 = '${base64}';\n`, 'utf-8');

process.stdout.write(`Inlined ${(bytes.length / 1024).toFixed(1)} KiB of wasm into src/generated/wasm-binary.ts\n`);
